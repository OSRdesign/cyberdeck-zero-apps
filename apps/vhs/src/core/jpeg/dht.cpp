const std::vector<std::uint8_t> &annex_k_dht()
{
    static const std::vector<std::uint8_t> seg = build();
    return seg;
}

bool ensure_dht(const std::uint8_t *p, std::size_t n, std::vector<std::uint8_t> &out, bool *inserted)
{
    if (inserted) *inserted = false;
    if (!p || n < 4 || p[0] != 0xFF || p[1] != 0xD8) return false;
    std::size_t i = 2;
    bool dht = false;
    while (i + 4 <= n) {
        if (p[i] != 0xFF) return false;
        const std::uint8_t m = p[i + 1];
        if (m == 0xFF) { /* fill byte */
            ++i;
            continue;
        }
        if (m == 0xD8 || (m >= 0xD0 && m <= 0xD7) || m == 0x01) {
            i += 2;
            continue;
        }
        if (m == 0xDA) { /* SOS */
            if (dht) {
                out.assign(p, p + n);
            } else {
                const std::vector<std::uint8_t> &t = annex_k_dht();
                out.clear();
                out.reserve(n + t.size());
                out.insert(out.end(), p, p + i);
                out.insert(out.end(), t.begin(), t.end());
                out.insert(out.end(), p + i, p + n);
                if (inserted) *inserted = true;
            }
            return true;
        }
        const std::size_t len = (static_cast<std::size_t>(p[i + 2]) << 8) | p[i + 3];
        if (len < 2 || i + 2 + len > n) return false;
        if (m == 0xC4) dht = true;
        i += 2 + len;
    }
    return false;
}

