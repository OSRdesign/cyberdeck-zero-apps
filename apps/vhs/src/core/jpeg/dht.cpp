void table(std::vector<std::uint8_t> &out, std::uint8_t tc_th, const std::uint8_t *bits, const std::uint8_t *vals)
{
    out.push_back(tc_th);
    int n = 0;
    for (int i = 0; i < 16; ++i) {
        out.push_back(bits[i]);
        n += bits[i];
    }
    out.insert(out.end(), vals, vals + n);
}

std::vector<std::uint8_t> build()
{
    std::vector<std::uint8_t> body;
    table(body, 0x00, kDcLumBits, kDcVals);
    table(body, 0x10, kAcLumBits, kAcLumVals);
    table(body, 0x01, kDcChrBits, kDcVals);
    table(body, 0x11, kAcChrBits, kAcChrVals);
    std::vector<std::uint8_t> seg = {0xFF, 0xC4};
    const std::size_t len = body.size() + 2;
    seg.push_back(static_cast<std::uint8_t>(len >> 8));
    seg.push_back(static_cast<std::uint8_t>(len & 0xFF));
    seg.insert(seg.end(), body.begin(), body.end());
    return seg;
}

