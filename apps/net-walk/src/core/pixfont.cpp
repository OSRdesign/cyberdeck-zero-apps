unsigned glyph_row(char c, int r)
{
    const Glyph *g = find(c);
    if (!g) g = find('?');
    if (r < 0 || r >= kGlyphRows) return 0;
    unsigned bits = 0;
    for (int i = 0; i < kGlyphCols; ++i) bits = (bits << 1) | (g->rows[r * kGlyphCols + i] == '#' ? 1u : 0u);
    return bits;
}

int text_width(const std::string &text)
{
    return text.empty() ? 0 : static_cast<int>(text.size()) * kAdvance - 1;
}

bool font_table_ok()
{
    const std::size_t n = sizeof kGlyphs / sizeof kGlyphs[0];
    for (std::size_t i = 0; i < n; ++i) {
        if (std::strlen(kGlyphs[i].rows) != static_cast<std::size_t>(kGlyphRows * kGlyphCols)) return false;
        for (std::size_t j = i + 1; j < n; ++j)
            if (kGlyphs[i].c == kGlyphs[j].c) return false;
    }
    return true;
}

bool has_glyphs(const std::string &text)
{
    for (char c : text)
        if (!find(c)) return false;
    return true;
}

